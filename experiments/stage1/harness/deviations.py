"""Reproduce the three deviations of nlip_sdk found in an earlier probe, and the nlip_server control reply (clause 6.3).

    uv run python -m stage1.harness.deviations      ->  results/stage1/deviations.md
Nothing is assumed: every line below is the output of a call made now, against the pinned code.
"""
from __future__ import annotations

import json

from stage1.harness.adapters import RESULTS, build_impls


def main() -> None:
    impls = {i.key: i for i in build_impls(["nlip_sdk", "nlip_server"])}
    sdk, ns = impls["nlip_sdk"].model, impls["nlip_server"].server
    out = ["# Deviations: raw evidence", "", "Generated by `stage1/harness/deviations.py` against the pinned commits; every line is the result of a call.", ""]
    try:
        out += ["## 1. Capitalised field names (ECMA-430 clause 5: capitalization is not relevant to the name or value of the field)", ""]
        for obj in (
            {"format": "text", "subformat": "English", "content": "Hi"},
            {"Format": "text", "Subformat": "English", "Content": "Hi"},
            {"FORMAT": "text", "SUBFORMAT": "English", "CONTENT": "Hi"},
            {"format": "Text", "subformat": "ENGLISH", "content": "Hi"},
        ):
            p = sdk.parse(obj)
            out.append(f"- `NLIP_Message.model_validate({json.dumps(obj)})` -> {'accepted' if p.accepted else 'REJECTED: ' + p.detail[:110]}")
        for obj in ({"Format": "text", "Subformat": "English", "Content": "Hi"},):
            r = ns.post("ack", obj)
            out.append(f"- `nlip_server` POST /nlip/ {json.dumps(obj)} -> HTTP {r.status}")
        out += ["", "## 2. Reserved token prefix (ECMA-430 6.2 and 6.2.2: 'authentication')", ""]
        info = sdk.d.call(op="info")
        out.append(f"- `ReservedTokens` in nlip_sdk: {json.dumps(info['reserved'])}")
        for sf in ("authentication", "authentication_x", "authorization", "authorization_x", "conversation", "conversation_abc"):
            out.append(f"- `is_auth({sf!r})` / `is_conv({sf!r})` -> {json.dumps(sdk.recognise(sf))}")
        out.append(f"- the token `add_authentication_token('tok123')` puts into a message: `{json.dumps(sdk.build('auth_token')['body'])}`")
        out += ["", "## 3. The `error` format (not in ECMA-430 Table 1)", ""]
        out.append(f"- `AllowedFormats` in nlip_sdk: {info['formats']}")
        out.append(f"- `NLIP_Factory.create_error_code('something failed')` builds: `{json.dumps(sdk.build('error')['body'])}`")
        p = sdk.parse({"format": "bogus", "subformat": "x", "content": "y"})
        out.append(f"- the first-level format is not checked: `format: bogus` -> {'accepted' if p.accepted else 'rejected'}")
        out += ["", "## 4. nlip_server and control messages (ECMA-430 6.3), and tokens (6.2), with a minimal application that answers 'ok'", ""]
        for body in (
            {"format": "text", "subformat": "English", "content": "q", "messagetype": "control"},
            {"format": "text", "subformat": "English", "content": "q", "control": True},
        ):
            r = ns.post("ack", body)
            out.append(f"- POST {json.dumps(body)} -> HTTP {r.status} `{r.text[:200]}`")
        for sf in ("conversation", "conversation_abc", "authentication_x", "authorization_x", "group_7"):
            body = {"format": "text", "subformat": "English", "content": "x", "submessages": [{"format": "token", "subformat": sf, "content": "V"}]}
            r = ns.post("ack", body)
            toks = [(x["subformat"], x["content"]) for x in ((r.body or {}).get("submessages") or []) if x["format"] == "token"]
            out.append(f"- token `{sf}` sent -> tokens in the answer: {toks}")
        r = ns.post("ack", {"format": "text", "subformat": "English", "content": "x"}, follow=False)
        out.append(f"- POST /nlip (no slash) -> HTTP {r.status}, Location: `{r.location}`")
    finally:
        for i in impls.values():
            i.close()
    (RESULTS / "deviations.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
